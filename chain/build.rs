use std::env;
use std::fs;
use std::path::Path;

use syn::parse::{Parse, ParseStream};
use syn::visit::{self, Visit};
use syn::{File, Ident, LitStr, Macro, Result, Token, Type};

#[derive(Debug)]
struct NumericTypeInfo {
    struct_name: String,
    lua_name: String,
}

struct DefineNumberTypeArgs {
    struct_name: Ident,
    _inner_type: Type,
    lua_name: LitStr,
}

impl Parse for DefineNumberTypeArgs {
    fn parse(input: ParseStream) -> Result<Self> {
        let struct_name: Ident = input.parse()?;
        input.parse::<Token![,]>()?;
        let inner_type: Type = input.parse()?;
        input.parse::<Token![,]>()?;
        let lua_name: LitStr = input.parse()?;

        Ok(DefineNumberTypeArgs {
            struct_name,
            _inner_type: inner_type,
            lua_name,
        })
    }
}

struct TypeVisitor {
    found_types: Vec<NumericTypeInfo>,
}

impl<'ast> Visit<'ast> for TypeVisitor {
    fn visit_macro(&mut self, mac: &'ast Macro) {
        if mac.path.is_ident("define_number_type") {
            match syn::parse2::<DefineNumberTypeArgs>(mac.tokens.clone()) {
                Ok(args) => {
                    self.found_types.push(NumericTypeInfo {
                        struct_name: args.struct_name.to_string(),
                        lua_name: args.lua_name.value(),
                    });
                }
                Err(e) => {
                    panic!("Failed to parse `define_number_type!` macro arguments: {}", e);
                }
            }
        }
        visit::visit_macro(self, mac);
    }
}

fn main() {
    let source_path = "src/vm/lvm/num.rs";
    println!("cargo:rerun-if-changed={}", source_path);

    let source_code = fs::read_to_string(source_path).expect("Failed to read source file.");
    let ast: File = syn::parse_file(&source_code).expect("Failed to parse source file.");

    let mut visitor = TypeVisitor {
        found_types: Vec::new(),
    };
    visitor.visit_file(&ast);

    visitor.found_types.push(NumericTypeInfo {
        struct_name: "LuaU256".to_string(),
        lua_name: "U256".to_string(),
    });

    let mut luau_output = String::new();
    luau_output.push_str("-- This file is automatically generated by build.rs. Do not edit.\n\n");

    for type_info in &visitor.found_types {
        luau_output.push_str(&format!("export type {} = {{\n", type_info.lua_name));
        
        let methods;
        
        if type_info.struct_name == "LuaU256" {
             methods = vec![
                ("add", "(self: U256, other: Numeric) -> Numeric"),
                ("sub", "(self: U256, other: Numeric) -> Numeric"),
                ("mul", "(self: U256, other: Numeric) -> Numeric"),
                ("div", "(self: U256, other: Numeric) -> Numeric"),
                ("bitand", "(self: U256, other: Numeric) -> Numeric"),
                ("bitor", "(self: U256, other: Numeric) -> Numeric"),
                ("bitxor", "(self: U256, other: Numeric) -> Numeric"),
                ("bitnot", "(self: U256) -> U256"),
                ("shl", "(self: U256, shift: number) -> Numeric"),
                ("shr", "(self: U256, shift: number) -> Numeric"),
                ("is_zero", "(self: U256) -> boolean"),
                ("is_max", "(self: U256) -> boolean"),
                ("leading_zeros", "(self: U256) -> number"),
                ("trailing_zeros", "(self: U256) -> number"),
                ("count_ones", "(self: U256) -> number"),
                ("to_string", "(self: U256) -> string"),
             ];
        } else {
            methods = vec![
                ("add", "(self: any, other: Numeric) -> Numeric"),
                ("sub", "(self: any, other: Numeric) -> Numeric"),
                ("mul", "(self: any, other: Numeric) -> Numeric"),
                ("div", "(self: any, other: Numeric) -> Numeric"),
                ("bitand", "(self: any, other: Numeric) -> Numeric"),
                ("bitor", "(self: any, other: Numeric) -> Numeric"),
                ("bitxor", "(self: any, other: Numeric) -> Numeric"),
                ("bitnot", "(self: any) -> any"),
                ("shl", "(self: any, shift: number) -> Numeric"),
                ("shr", "(self: any, shift: number) -> Numeric"),
                ("value", "(self: any) -> any"),
                ("is_zero", "(self: any) -> boolean"),
                ("is_max", "(self: any) -> boolean"),
                ("leading_zeros", "(self: any) -> number"),
                ("trailing_zeros", "(self: any) -> number"),
                ("count_ones", "(self: any) -> number"),
                ("to_string", "(self: any) -> string"),
                ("reverse_bits", "(self: any) -> any"),
                ("swap_bytes", "(self: any) -> any"),
            ];
        }

        let metamethods = vec![
            ("__add", "(self: any, other: Numeric) -> Numeric"),
            ("__sub", "(self: any, other: Numeric) -> Numeric"),
            ("__mul", "(self: any, other: Numeric) -> Numeric"),
            ("__div", "(self: any, other: Numeric) -> Numeric"),
            ("__eq", "(self: any, other: Numeric) -> boolean"),
            ("__lt", "(self: any, other: Numeric) -> boolean"),
            ("__le", "(self: any, other: Numeric) -> boolean"),
            ("__tostring", "(self: any) -> string"),
        ];
        
        for (name, signature) in &methods {
            let specific_sig = signature.replace("any", &type_info.lua_name);
            luau_output.push_str(&format!("    {}: {},\n", name, specific_sig));
        }

        for (name, signature) in &metamethods {
            let specific_sig = signature.replace("any", &type_info.lua_name);
            luau_output.push_str(&format!("    {}: {},\n", name, specific_sig));
        }

        luau_output.push_str("}\n\n");
    }

    let all_type_names: Vec<String> = visitor.found_types.iter().map(|t| t.lua_name.clone()).collect();
    luau_output.push_str(&format!("export type Numeric = {}\n\n", all_type_names.join(" | ")));
    

    let out_dir = env::var("OUT_DIR").unwrap();
    let dest_path = Path::new(&out_dir).join("luau_types.lua");
    fs::write(&dest_path, luau_output).expect("Failed to write Luau types file.");

    println!("cargo:rerun-if-changed=build.rs");
}